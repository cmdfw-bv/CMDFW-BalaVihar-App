#!/usr/bin/env node
// Regenerates the ADR index block in .docs/adr/README.md FROM the ADR files themselves.
// The files are the single source of truth: each ADR's id (H1), title (H1), Status, Category, and
// Date are read from its header, grouped by Category, and written between the ADR-INDEX markers.
// Run: `npm run gen:adr-index`. CI runs it with --check and fails if the committed index is stale
// (so the index can never drift from the files). See ADR-2026-08-21-adr-identifier-scheme.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ADR_DIR = path.join(ROOT, '.docs/adr');
const README = path.join(ADR_DIR, 'README.md');

// Display order + emoji for the category groups. Any ADR whose Category isn't here lands in "Other".
const CATEGORIES = [
  ['UX', '🎨 Usability & Design (UX)'],
  ['Auth/Access', '🔐 Auth & Access Control'],
  ['Data', '🗄️ Data Model & DB Logic'],
  ['Privacy/Minors', '🛡️ Privacy & Minors’ Data'],
  ['Chat/Notifications', '💬 Chat & Notifications'],
  ['Infra/Process', '⚙️ Infrastructure, Delivery & Process'],
];
const START = '<!-- ADR-INDEX:START (generated by scripts/gen-adr-index.mjs — do not edit by hand) -->';
const END = '<!-- ADR-INDEX:END -->';

const field = (text, name) => {
  const m = text.match(new RegExp(`\\*\\*${name}:\\*\\*\\s*(.+?)\\s*(?:·\\s*\\*\\*|$)`, 'm'));
  return m ? m[1].trim() : '';
};

const adrs = fs.readdirSync(ADR_DIR)
  .filter((f) => /^(\d{4}-|\d{4}-\d{2}-\d{2}-).*\.md$/.test(f))
  .map((f) => {
    const text = fs.readFileSync(path.join(ADR_DIR, f), 'utf8');
    const h1 = text.match(/^#\s+(ADR-\S+):\s*(.+?)\s*$/m);
    return {
      file: f,
      id: h1 ? h1[1] : f.replace(/\.md$/, ''),
      title: h1 ? h1[2] : '(untitled)',
      status: field(text, 'Status') || '—',
      category: field(text, 'Category') || 'Other',
      date: field(text, 'Date') || '—',
    };
  });

const byCat = new Map();
for (const a of adrs) {
  if (!byCat.has(a.category)) byCat.set(a.category, []);
  byCat.get(a.category).push(a);
}
// stable order within a group: by date, then id
for (const list of byCat.values()) list.sort((a, b) => (a.date + a.id).localeCompare(b.date + b.id));

const groups = [
  ...CATEGORIES.filter(([key]) => byCat.has(key)),
  ...[...byCat.keys()].filter((k) => !CATEGORIES.some(([key]) => key === k)).map((k) => [k, `📁 ${k}`]),
];

const esc = (s) => s.replace(/\|/g, '\\|');
let out = `_Generated from the ADR files by \`npm run gen:adr-index\` — do not edit this block by hand (edit the ADRs). ${adrs.length} decisions._\n`;
for (const [key, heading] of groups) {
  const list = byCat.get(key) || [];
  if (!list.length) continue;
  out += `\n### ${heading}\n\n| ID | Decision | Status | Date |\n|---|---|---|---|\n`;
  for (const a of list) out += `| [${a.id}](${a.file}) | ${esc(a.title)} | ${esc(a.status)} | ${a.date} |\n`;
}

const block = `${START}\n\n${out.trimEnd()}\n\n${END}`;
let readme = fs.readFileSync(README, 'utf8');
if (readme.includes(START) && readme.includes(END)) {
  readme = readme.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), block);
} else {
  readme = readme.replace(/## Index\n[\s\S]*?(?=\n## )/, `## Index\n\n${block}\n`);
}

if (process.argv.includes('--check')) {
  const current = fs.readFileSync(README, 'utf8');
  if (current !== readme) {
    console.error('✗ .docs/adr/README.md is out of sync with the ADR files. Run `npm run gen:adr-index` and commit.');
    process.exit(1);
  }
  console.log('✓ ADR index is in sync with the files.');
} else {
  fs.writeFileSync(README, readme);
  console.log(`✓ Regenerated ADR index (${adrs.length} ADRs across ${groups.filter(([k]) => (byCat.get(k) || []).length).length} categories).`);
}
